import { chromium } from 'playwright';
import { mkdirSync, writeFileSync } from 'node:fs';
const base='http://127.0.0.1:3150'; const dir='evidence/product/assets/as-006'; mkdirSync(dir,{recursive:true});
const browser=await chromium.launch();
const page=await browser.newPage({viewport:{width:1440,height:900}});
const errors=[]; page.on('pageerror',e=>errors.push(e.message)); page.on('console',m=>{if(m.type()==='error')errors.push(m.text());});
const path=[];
async function goto(url,label,wait=900){ await page.goto(base+url,{waitUntil:'load'}); await page.waitForTimeout(wait); path.push(label); }
async function shot(name,full=false){ await page.screenshot({path:`${dir}/${name}.png`,fullPage:full}); }
await goto('/','overview'); await shot('01-overview-1440');
await goto('/opportunities/scn-scent-layering.analysis.main','opportunity'); await shot('02-opportunity-detail-1440');
await goto('/campaigns/scn-scent-layering.brief.main/brief','brief'); await shot('03-campaign-brief-1440');
await goto('/atelier?campaignId=scn-scent-layering.brief.main&language=en','atelier-en',1400); await shot('04-atelier-en-1440');
const video=page.getByTestId('provided-video');
await page.waitForFunction(()=>{const v=document.querySelector('[data-testid="provided-video"]');return v&&v.readyState>=1&&v.duration>0;});
const media=await video.evaluate(v=>({controls:v.controls,width:v.videoWidth,height:v.videoHeight,duration:v.duration,fit:getComputedStyle(v).objectFit}));
await video.evaluate(v=>{v.muted=true;});
await video.evaluate(async v=>{await v.play();});
await page.waitForFunction(()=>document.querySelector('[data-testid="provided-video"]').currentTime>0.2);
const played=await video.evaluate(v=>v.currentTime);
await video.evaluate(v=>v.pause());
const paused=await video.evaluate(v=>v.paused);
await video.evaluate(v=>{v.currentTime=7.56;});
await page.waitForFunction(()=>Math.abs(document.querySelector('[data-testid="provided-video"]').currentTime-7.56)<0.25);
await shot('05-atelier-video-seek-1440');
await video.evaluate(async v=>{v.currentTime=0;await v.play();});
await page.waitForFunction(()=>document.querySelector('[data-testid="provided-video"]').currentTime>0.1);
await video.evaluate(v=>v.pause());
await video.evaluate(v=>{v.currentTime=0;});
await goto('/atelier?campaignId=scn-scent-layering.brief.main&language=ar','atelier-ar',1400); await shot('06-atelier-ar-1440');
await goto('/library','library'); await shot('07-library-1440');
await page.getByTestId('LIB-provided-preview-final_preview_video').click(); await page.waitForTimeout(700); await shot('08-library-provided-video-preview-1440');
await page.getByTestId('LIB-provided-close').click();
await goto('/deliverables','deliverables'); await shot('09-deliverables-1440');
await page.setViewportSize({width:1366,height:768});
await goto('/','overview-1366'); await shot('10-overview-1366');
await goto('/campaigns/scn-scent-layering.brief.main/brief','brief-1366'); await shot('11-campaign-brief-1366');
await goto('/atelier?campaignId=scn-scent-layering.brief.main&language=en','atelier-1366',1200); await shot('12-atelier-en-1366');
await page.setViewportSize({width:390,height:844});
await goto('/','overview-390'); await shot('13-overview-390',true);
await goto('/atelier?campaignId=scn-scent-layering.brief.main&language=ar','atelier-ar-390',1200); await shot('14-atelier-ar-390',true);
await goto('/library','library-390'); await shot('15-library-390',true);
const overflow=await page.evaluate(()=>document.documentElement.scrollWidth-window.innerWidth);
await browser.close();
writeFileSync(dir+'/click-path-observations.json',JSON.stringify({checkedAt:new Date().toISOString(),base,path,media,played,paused,seekedTo:7.56,overflow390:overflow,errors},null,2)+'\n');
