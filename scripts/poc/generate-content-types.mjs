#!/usr/bin/env node
/*
 * Generate TypeScript declarations for the content-only input profile from the
 * read-only main-control schema. The original scenario schema and generated
 * types are not touched.
 *
 * Usage: node scripts/poc/generate-content-types.mjs [--check]
 */
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { compile } from 'json-schema-to-typescript';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const SCHEMA_FILE = path.join(ROOT, 'contracts', 'poc', 'content-only.schema.json');
const OUTPUT_DIR = path.join(ROOT, 'apps', 'web', 'demo', 'poc', 'generated');
const TYPES_FILE = 'content-only.types.ts';
const MANIFEST_FILE = 'content-only.manifest.json';
const checkOnly = process.argv.includes('--check');
const unknown = process.argv.slice(2).filter((arg) => arg !== '--check');
if (unknown.length) {
  console.error(`Unknown argument(s): ${unknown.join(' ')}`);
  process.exit(2);
}
const sha256 = (buffer) => createHash('sha256').update(buffer).digest('hex');

function collectPrefixItems(node, found = []) {
  if (!node || typeof node !== 'object') return found;
  if (Array.isArray(node.prefixItems)) found.push(node.prefixItems);
  for (const value of Object.values(node)) {
    if (value && typeof value === 'object') collectPrefixItems(value, found);
  }
  return found;
}

function schemaToTsType(schema) {
  if (!schema || typeof schema !== 'object') return 'unknown';
  if (schema.const !== undefined) return JSON.stringify(schema.const);
  if (Array.isArray(schema.enum)) return schema.enum.map((value) => JSON.stringify(value)).join(' | ');
  if (schema.$ref) {
    const name = String(schema.$ref).split('/').pop();
    return name.replace(/(^|[-_])([a-z])/g, (_, prefix, letter) => `${prefix}${letter.toUpperCase()}`);
  }
  switch (schema.type) {
    case 'string': return 'string';
    case 'integer':
    case 'number': return 'number';
    case 'boolean': return 'boolean';
    case 'null': return 'null';
    case 'array': return `${schemaToTsType(schema.items)}[]`;
    case 'object': return 'Record<string, unknown>';
    default: return 'unknown';
  }
}

async function main() {
  const schemaBytes = readFileSync(SCHEMA_FILE);
  const schemaSha = sha256(schemaBytes);
  const schema = JSON.parse(schemaBytes.toString('utf8'));
  const starter = 'contentOnlyScenarioPackage';
  const banner = `/**
 * AUTO-GENERATED by scripts/poc/generate-content-types.mjs — do not edit.
 * Source: contracts/poc/content-only.schema.json
 * Schema SHA-256: ${schemaSha} (${schemaBytes.length} bytes)
 */`;
  const compiled = await compile(schema, starter, {
    bannerComment: banner,
    additionalProperties: false,
    declareExternallyReferenced: true,
    enableConstEnums: false,
    format: false,
    strictIndexSignatures: false,
    unreachableDefinitions: true,
    style: { singleQuote: true, semi: true, tabWidth: 2, printWidth: 100 },
  });
  let typesContent = `${compiled.trimEnd()}\n`;
  const prefixItems = collectPrefixItems(schema);
  const neverIndexes = [...typesContent.matchAll(/never\[\]/g)].map((match) => match.index ?? -1);
  if (prefixItems.length > 0) {
    if (neverIndexes.length !== prefixItems.length) {
      throw new Error(`Type generator could not map prefixItems tuples: ${prefixItems.length} tuple(s), ${neverIndexes.length} placeholder(s).`);
    }
    let offset = 0;
    prefixItems.forEach((items, index) => {
      const position = neverIndexes[index] + offset;
      const replacement = `[${items.map((item) => schemaToTsType(item)).join(', ')}]`;
      typesContent = typesContent.slice(0, position) + replacement + typesContent.slice(position + 'never[]'.length);
      offset += replacement.length - 'never[]'.length;
    });
  }
  const typesSha = sha256(Buffer.from(typesContent, 'utf8'));
  const manifest = {
    generator: 'scripts/poc/generate-content-types.mjs',
    source: 'contracts/poc/content-only.schema.json',
    schemaSha256: schemaSha,
    schemaBytes: schemaBytes.length,
    typesFile: TYPES_FILE,
    typesSha256: typesSha,
    typesBytes: Buffer.byteLength(typesContent, 'utf8'),
  };
  const manifestContent = `${JSON.stringify(manifest, null, 2)}\n`;
  const expected = new Map([[TYPES_FILE, typesContent], [MANIFEST_FILE, manifestContent]]);
  if (checkOnly) {
    let failed = false;
    for (const [file, content] of expected) {
      const full = path.join(OUTPUT_DIR, file);
      if (!existsSync(full) || readFileSync(full, 'utf8') !== content) {
        console.error(`${file}: out of date or missing`);
        failed = true;
      }
    }
    if (failed) process.exit(1);
    console.log(`Content-only generated types are up to date (schema sha256 ${schemaSha}).`);
    return;
  }
  mkdirSync(OUTPUT_DIR, { recursive: true });
  for (const [file, content] of expected) writeFileSync(path.join(OUTPUT_DIR, file), content, 'utf8');
  console.log(`Wrote ${expected.size} content-only generated file(s).`);
  console.log(`Schema sha256: ${schemaSha}`);
  console.log(`Types sha256:  ${typesSha}`);
}
main().catch((error) => {
  console.error(error instanceof Error ? error.message : String(error));
  process.exit(1);
});
